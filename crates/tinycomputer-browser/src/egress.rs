//! Session-local browser HTTP proxy with destination authorization before each dial.
//!
//! The proxy accepts only browser HTTP proxy requests. It never resolves a name
//! locally: the authorizer returns a finite set of vetted socket addresses and
//! the proxy consumes the grant before dialing one exact address.

use std::{future::Future, io, net::SocketAddr, pin::Pin, sync::Arc, time::Duration};

use base64::Engine as _;
use tokio::{
    io::{AsyncReadExt, AsyncWriteExt, copy_bidirectional},
    net::{TcpListener, TcpStream},
    task::JoinSet,
};

/// A destination parsed from the browser's actual proxy request.
#[derive(Clone, PartialEq, Eq)]
pub struct BrowserDialTarget {
    /// `http` or `https`.
    pub scheme: String,
    /// Canonical host, without brackets for IPv6 literals.
    pub hostname: String,
    /// Effective destination port.
    pub port: u16,
    /// Opaque per-browser-session binding generated by `TinyComputer`.
    pub session_id: String,
}

impl std::fmt::Debug for BrowserDialTarget {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str("BrowserDialTarget([REDACTED])")
    }
}

/// Opaque authorizer state plus the exact permitted sockets.
#[derive(Clone)]
pub struct DialGrant {
    /// Opaque lease returned by the authenticated `TinySecurity` adapter.
    pub lease: String,
    /// Finite address set vetted by `TinySecurity`.
    pub addresses: Vec<SocketAddr>,
}

impl std::fmt::Debug for DialGrant {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str("DialGrant([REDACTED])")
    }
}

/// The host adapter delegates every decision to `TinySecurity` over `TinyBus`.
pub trait EgressAuthorizer: Send + Sync + 'static {
    /// Authorize the actual destination and return a one-use grant.
    fn authorize(
        &self,
        target: BrowserDialTarget,
    ) -> Pin<Box<dyn Future<Output = io::Result<DialGrant>> + Send>>;
    /// Consume the grant before the selected socket is opened.
    fn consume(
        &self,
        target: BrowserDialTarget,
        grant: DialGrant,
        address: SocketAddr,
    ) -> Pin<Box<dyn Future<Output = io::Result<()>> + Send>>;
    /// Revalidate an active tunnel lease. False or error closes the tunnel.
    fn validate(&self, lease: String) -> Pin<Box<dyn Future<Output = io::Result<bool>> + Send>>;
}

/// An ephemeral loopback proxy owned by one browser session.
#[derive(Debug)]
pub struct EgressProxy {
    address: SocketAddr,
    task: tokio::task::JoinHandle<()>,
}

impl EgressProxy {
    /// Bind a private IPv4 loopback listener for one session.
    ///
    /// # Errors
    ///
    /// Returns an I/O error when the listener cannot bind or its address cannot
    /// be read.
    pub async fn bind(
        authorizer: Arc<dyn EgressAuthorizer>,
        session_id: String,
        proxy_password: String,
    ) -> io::Result<Self> {
        let listener = TcpListener::bind(("127.0.0.1", 0)).await?;
        let address = listener.local_addr()?;
        let task = tokio::spawn(async move {
            let mut connections = JoinSet::new();
            loop {
                tokio::select! {
                    accepted = listener.accept(), if connections.len() < 64 => {
                        let Ok((stream, _)) = accepted else { break; };
                        let auth = authorizer.clone();
                        let session = session_id.clone();
                        let password = proxy_password.clone();
                        connections.spawn(async move { let _ = serve(stream, auth, session, password).await; });
                    }
                    _ = connections.join_next(), if !connections.is_empty() => {}
                }
            }
        });
        Ok(Self { address, task })
    }

    /// Chromium proxy URL; it contains no policy authority.
    #[must_use]
    pub fn url(&self) -> String {
        format!("http://{}:{}", self.address.ip(), self.address.port())
    }
}

impl Drop for EgressProxy {
    fn drop(&mut self) {
        self.task.abort();
    }
}

async fn serve(
    mut client: TcpStream,
    auth: Arc<dyn EgressAuthorizer>,
    session_id: String,
    proxy_password: String,
) -> io::Result<()> {
    let Some(mut request) = read_proxy_request(&mut client, &session_id, &proxy_password).await?
    else {
        return Ok(());
    };
    if !read_request_body(&mut client, &mut request).await? {
        return refuse(&mut client).await;
    }
    let Some(first_grant) = authorize(&auth, &request.target).await else {
        return refuse(&mut client).await;
    };
    let addresses = first_grant.addresses.clone();
    let mut connected = None;
    for (index, address) in addresses.into_iter().enumerate() {
        // A consume call spends its one-use grant. Reauthorize every later
        // candidate so a failed dial cannot reuse a spent authorization.
        let grant = if index == 0 {
            first_grant.clone()
        } else {
            match authorize(&auth, &request.target).await {
                Some(grant) if grant.addresses.contains(&address) => grant,
                _ => continue,
            }
        };
        if !matches!(
            tokio::time::timeout(
                Duration::from_secs(5),
                auth.consume(request.target.clone(), grant.clone(), address),
            )
            .await,
            Ok(Ok(()))
        ) {
            return refuse(&mut client).await;
        }
        if let Ok(Ok(upstream)) =
            tokio::time::timeout(Duration::from_secs(5), TcpStream::connect(address)).await
        {
            connected = Some((upstream, grant.lease));
            break;
        }
    }
    let Some((mut upstream, lease)) = connected else {
        return refuse(&mut client).await;
    };
    if !validate_lease(&auth, &lease).await? {
        return Ok(());
    }
    initialize_upstream(&mut client, &mut upstream, &request).await?;
    if request.connect || request.has_upgrade {
        tunnel_with_lease(&mut client, &mut upstream, &auth, lease).await?;
    } else {
        forward_response_with_lease(&mut client, &mut upstream, &auth, lease).await?;
    }
    Ok(())
}

async fn authorize(
    auth: &Arc<dyn EgressAuthorizer>,
    target: &BrowserDialTarget,
) -> Option<DialGrant> {
    match tokio::time::timeout(Duration::from_secs(5), auth.authorize(target.clone())).await {
        Ok(Ok(grant)) if !grant.addresses.is_empty() && grant.addresses.len() <= 64 => Some(grant),
        _ => None,
    }
}

struct ProxyRequest {
    bytes: Vec<u8>,
    split: usize,
    lines: Vec<String>,
    method: String,
    uri: String,
    version: String,
    target: BrowserDialTarget,
    connect: bool,
    body_len: usize,
    has_upgrade: bool,
}

async fn read_proxy_request(
    client: &mut TcpStream,
    session_id: &str,
    proxy_password: &str,
) -> io::Result<Option<ProxyRequest>> {
    let mut bytes = Vec::with_capacity(4096);
    let mut chunk = [0u8; 1024];
    loop {
        let n = tokio::time::timeout(Duration::from_secs(10), client.read(&mut chunk))
            .await
            .map_err(|_| io::Error::new(io::ErrorKind::TimedOut, "proxy request timed out"))??;
        if n == 0 {
            return Ok(None);
        }
        bytes.extend_from_slice(&chunk[..n]);
        if bytes.len() > 32 * 1024 {
            refuse(client).await?;
            return Ok(None);
        }
        if bytes.windows(4).any(|window| window == b"\r\n\r\n") {
            break;
        }
    }
    let Some(header_end) = bytes.windows(4).position(|window| window == b"\r\n\r\n") else {
        refuse(client).await?;
        return Ok(None);
    };
    let split = header_end + 4;
    let Ok(head) = std::str::from_utf8(&bytes[..split]) else {
        refuse(client).await?;
        return Ok(None);
    };
    let lines: Vec<String> = head.split("\r\n").map(str::to_owned).collect();
    let Some(request_line) = lines.first() else {
        refuse(client).await?;
        return Ok(None);
    };
    let mut parts = request_line.split_ascii_whitespace();
    let method = parts.next().unwrap_or_default().to_owned();
    let uri = parts.next().unwrap_or_default().to_owned();
    let version = parts.next().unwrap_or_default().to_owned();
    if parts.next().is_some() || (version != "HTTP/1.1" && version != "HTTP/1.0") {
        refuse(client).await?;
        return Ok(None);
    }
    let Some(target) = proxy_target(&method, &uri, session_id) else {
        refuse(client).await?;
        return Ok(None);
    };
    let connect = method.eq_ignore_ascii_case("CONNECT");
    let Some(headers) = parse_proxy_headers(&lines, &target, connect, session_id) else {
        refuse(client).await?;
        return Ok(None);
    };
    if !has_proxy_auth(headers.proxy_authorization.as_deref(), proxy_password) {
        write_all_bounded(
            client,
            b"HTTP/1.1 407 Proxy Authentication Required\r\nProxy-Authenticate: Basic realm=\"tinycomputer-browser\"\r\nConnection: close\r\nContent-Length: 0\r\n\r\n",
            "browser proxy challenge timed out",
        )
        .await?;
        return Ok(None);
    }
    if connect && bytes.len() > split {
        refuse(client).await?;
        return Ok(None);
    }
    Ok(Some(ProxyRequest {
        bytes,
        split,
        lines,
        method,
        uri,
        version,
        target,
        connect,
        body_len: headers.body_len,
        has_upgrade: headers.has_upgrade,
    }))
}

fn proxy_target(method: &str, uri: &str, session_id: &str) -> Option<BrowserDialTarget> {
    if method.eq_ignore_ascii_case("CONNECT") {
        return parse_authority(uri, "https", session_id).ok();
    }
    let url = url::Url::parse(uri).ok()?;
    if !matches!(url.scheme(), "http" | "ws")
        || !url.username().is_empty()
        || url.password().is_some()
        || url.fragment().is_some()
    {
        return None;
    }
    Some(BrowserDialTarget {
        scheme: "http".to_owned(),
        hostname: url
            .host_str()?
            .trim_matches(['[', ']'])
            .to_ascii_lowercase(),
        port: url.port_or_known_default()?,
        session_id: session_id.to_owned(),
    })
}

struct ParsedHeaders {
    body_len: usize,
    has_upgrade: bool,
    proxy_authorization: Option<String>,
}

fn parse_proxy_headers(
    lines: &[String],
    target: &BrowserDialTarget,
    connect: bool,
    session_id: &str,
) -> Option<ParsedHeaders> {
    let mut body_len = 0usize;
    let mut host_header = None;
    let mut has_upgrade = false;
    let mut connection_upgrade = false;
    let mut proxy_authorization = None;
    let mut saw_content_length = false;
    for line in lines
        .iter()
        .skip(1)
        .map(String::as_str)
        .filter(|line| !line.is_empty())
    {
        let (name, value) = line.split_once(':')?;
        if name.eq_ignore_ascii_case("host") {
            if host_header.replace(value.trim().to_owned()).is_some() {
                return None;
            }
        } else if name.eq_ignore_ascii_case("content-length") {
            if saw_content_length {
                return None;
            }
            saw_content_length = true;
            body_len = value.trim().parse().unwrap_or(usize::MAX);
        } else if name.eq_ignore_ascii_case("transfer-encoding")
            || name.eq_ignore_ascii_case("expect")
        {
            return None;
        } else if name.eq_ignore_ascii_case("proxy-authorization") {
            if proxy_authorization
                .replace(value.trim().to_owned())
                .is_some()
            {
                return None;
            }
        } else if name.eq_ignore_ascii_case("upgrade")
            && value.trim().eq_ignore_ascii_case("websocket")
        {
            has_upgrade = true;
        } else if name.eq_ignore_ascii_case("connection")
            && value
                .split(',')
                .any(|token| token.trim().eq_ignore_ascii_case("upgrade"))
        {
            connection_upgrade = true;
        }
    }
    let host_matches = host_header.as_deref().is_some_and(|host| {
        parse_authority(host, if connect { "https" } else { "http" }, session_id)
            .is_ok_and(|parsed| parsed.hostname == target.hostname && parsed.port == target.port)
    });
    if has_upgrade != connection_upgrade
        || !host_matches
        || (connect && body_len != 0)
        || (!connect && (body_len > 1024 * 1024 || (has_upgrade && body_len != 0)))
    {
        return None;
    }
    Some(ParsedHeaders {
        body_len,
        has_upgrade,
        proxy_authorization,
    })
}

fn has_proxy_auth(proxy_authorization: Option<&str>, password: &str) -> bool {
    let expected = format!(
        "Basic {}",
        base64::engine::general_purpose::STANDARD.encode(format!("tinycomputer:{password}"))
    );
    proxy_authorization
        .is_some_and(|actual| constant_time_eq(actual.as_bytes(), expected.as_bytes()))
}

async fn initialize_upstream(
    client: &mut TcpStream,
    upstream: &mut TcpStream,
    request: &ProxyRequest,
) -> io::Result<()> {
    if request.connect {
        write_all_bounded(
            client,
            b"HTTP/1.1 200 Connection Established\r\n\r\n",
            "browser CONNECT response timed out",
        )
        .await?;
        if request.bytes.len() > request.split {
            return write_all_bounded(
                upstream,
                &request.bytes[request.split..],
                "browser CONNECT payload timed out",
            )
            .await;
        }
        return Ok(());
    }
    let url = url::Url::parse(&request.uri)
        .map_err(|_| io::Error::new(io::ErrorKind::InvalidData, "invalid HTTP proxy URL"))?;
    let path = if let Some(query) = url.query() {
        format!("{}?{query}", url.path())
    } else {
        url.path().to_owned()
    };
    let mut forwarded = format!("{} {path} {}\r\n", request.method, request.version);
    for line in request
        .lines
        .iter()
        .skip(1)
        .map(String::as_str)
        .filter(|line| !line.is_empty())
    {
        let name = line.split_once(':').map_or("", |(name, _)| name);
        if !name.eq_ignore_ascii_case("connection")
            && !name.eq_ignore_ascii_case("proxy-connection")
            && !name.eq_ignore_ascii_case("proxy-authorization")
        {
            forwarded.push_str(line);
            forwarded.push_str("\r\n");
        }
    }
    if request.has_upgrade {
        forwarded.push_str("Connection: Upgrade\r\n\r\n");
    } else {
        forwarded.push_str("Connection: close\r\n\r\n");
    }
    write_all_bounded(
        upstream,
        forwarded.as_bytes(),
        "browser upstream request timed out",
    )
    .await?;
    write_all_bounded(
        upstream,
        &request.bytes[request.split..],
        "browser upstream body timed out",
    )
    .await
}

async fn read_request_body(client: &mut TcpStream, request: &mut ProxyRequest) -> io::Result<bool> {
    if request.has_upgrade || request.connect {
        return Ok(true);
    }
    let received = request.bytes.len().saturating_sub(request.split);
    if received > request.body_len {
        return Ok(false);
    }
    let mut chunk = [0u8; 1024];
    while request.bytes.len().saturating_sub(request.split) < request.body_len {
        let n = tokio::time::timeout(Duration::from_secs(10), client.read(&mut chunk))
            .await
            .map_err(|_| io::Error::new(io::ErrorKind::TimedOut, "proxy body timed out"))??;
        if n == 0 {
            return Ok(false);
        }
        request.bytes.extend_from_slice(&chunk[..n]);
        if request.bytes.len() > request.split + request.body_len {
            return Ok(false);
        }
    }
    Ok(true)
}

fn constant_time_eq(left: &[u8], right: &[u8]) -> bool {
    let mut difference = left.len() ^ right.len();
    for index in 0..left.len().max(right.len()) {
        difference |= usize::from(
            left.get(index).copied().unwrap_or(0) ^ right.get(index).copied().unwrap_or(0),
        );
    }
    difference == 0
}

async fn tunnel_with_lease(
    client: &mut TcpStream,
    upstream: &mut TcpStream,
    auth: &Arc<dyn EgressAuthorizer>,
    lease: String,
) -> io::Result<()> {
    let relay = copy_bidirectional(client, upstream);
    tokio::pin!(relay);
    let mut validations = validation_interval();
    loop {
        tokio::select! {
            biased;
            _ = validations.tick() => {
                if !validate_lease(auth, &lease).await? { return Ok(()); }
            },
            result = &mut relay => { result?; return Ok(()); },
        }
    }
}

async fn forward_response_with_lease(
    client: &mut TcpStream,
    upstream: &mut TcpStream,
    auth: &Arc<dyn EgressAuthorizer>,
    lease: String,
) -> io::Result<()> {
    let mut chunk = [0u8; 8192];
    let mut validations = validation_interval();
    loop {
        tokio::select! {
            biased;
            _ = validations.tick() => {
                if !validate_lease(auth, &lease).await? { return Ok(()); }
            },
            result = upstream.read(&mut chunk) => {
                let n = result?;
                if n == 0 { return Ok(()); }
                write_all_bounded(client, &chunk[..n], "browser response write timed out").await?;
            },
        }
    }
}

fn validation_interval() -> tokio::time::Interval {
    let period = Duration::from_secs(1);
    let mut interval = tokio::time::interval_at(tokio::time::Instant::now() + period, period);
    interval.set_missed_tick_behavior(tokio::time::MissedTickBehavior::Skip);
    interval
}

async fn validate_lease(auth: &Arc<dyn EgressAuthorizer>, lease: &str) -> io::Result<bool> {
    tokio::time::timeout(Duration::from_secs(2), auth.validate(lease.to_owned()))
        .await
        .map_err(|_| {
            io::Error::new(
                io::ErrorKind::TimedOut,
                "browser lease validation timed out",
            )
        })?
}

pub(super) fn parse_authority(
    value: &str,
    scheme: &str,
    session_id: &str,
) -> io::Result<BrowserDialTarget> {
    if value.contains("://") {
        return Err(io::Error::new(
            io::ErrorKind::InvalidData,
            "authority form required",
        ));
    }
    let authority = url::Url::parse(&format!("{scheme}://{value}/"))
        .map_err(|_| io::Error::new(io::ErrorKind::InvalidData, "invalid CONNECT authority"))?;
    if authority.path() != "/"
        || authority.query().is_some()
        || authority.fragment().is_some()
        || !authority.username().is_empty()
        || authority.password().is_some()
    {
        return Err(io::Error::new(
            io::ErrorKind::InvalidData,
            "invalid CONNECT authority",
        ));
    }
    Ok(BrowserDialTarget {
        scheme: scheme.to_owned(),
        hostname: authority
            .host_str()
            .unwrap_or_default()
            .trim_matches(['[', ']'])
            .to_ascii_lowercase(),
        port: authority
            .port()
            .unwrap_or(if scheme == "http" { 80 } else { 443 }),
        session_id: session_id.to_owned(),
    })
}

async fn refuse(client: &mut TcpStream) -> io::Result<()> {
    write_all_bounded(
        client,
        b"HTTP/1.1 403 Forbidden\r\nConnection: close\r\nContent-Length: 0\r\n\r\n",
        "browser refusal response timed out",
    )
    .await
}

async fn write_all_bounded(
    stream: &mut TcpStream,
    bytes: &[u8],
    message: &'static str,
) -> io::Result<()> {
    tokio::time::timeout(Duration::from_secs(5), stream.write_all(bytes))
        .await
        .map_err(|_| io::Error::new(io::ErrorKind::TimedOut, message))?
}
